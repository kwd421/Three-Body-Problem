from pathlib import Path
from playwright.sync_api import sync_playwright
import json, copy
BASE=Path(__file__).resolve().parent
HTML=BASE.parent/'three_body_lab_v1_2.html'
results=[]
def check(name,value,detail=None):
    results.append({'name':name,'passed':bool(value),'details':detail})
    print(('PASS ' if value else 'FAIL ')+name,detail or '')
    if not value: raise AssertionError(name)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1500,'height':1100},accept_downloads=True)
    page=context.new_page();errors=[];requests=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:requests.append(r.url))
    page.set_content(HTML.read_text());page.wait_for_function('!!window.ThreeBodyProofUI')
    page.evaluate('ThreeBodyLab.pause()')
    check('v1.2 proof module initialized',page.locator('.version').inner_text()=='v1.2')
    state0=page.evaluate('ThreeBodyLab.config()')
    page.click('#open-proof')
    check('proof dialog opens and simulation pauses',page.locator('#proof-modal').is_visible() and not page.evaluate('ThreeBodyLab.state().playing'))
    page.fill('#proof-time','.1');page.select_option('#proof-order','12');page.select_option('#proof-step','7');page.click('#proof-run')
    page.wait_for_function('ThreeBodyProofUI.result!==null',timeout=20000)
    result=page.evaluate('ThreeBodyProofUI.result')
    check('single certificate completes',result['checks'][0]['verified'] and result['checks'][0]['complete'])
    check('13 proof steps at T=.1',result['checks'][0]['steps']==13)
    check('computed enclosure is narrow',result['checks'][0]['maxPositionWidth']<4e-24)
    check('physics initial state unchanged',page.evaluate('ThreeBodyLab.config().y')==state0['y'])
    check('positive all-time distance lower bound',float(result['checks'][0]['minDistanceLower'])>1.37)
    with page.expect_download() as event: page.click('#proof-export')
    event.value.save_as(str(BASE/'browser_download_certificate.json'))
    loaded=json.loads((BASE/'browser_download_certificate.json').read_text())
    check('actual certificate download',loaded['steps']==result['record']['steps'])
    # A dishonest summary must not affect recalculated facts.
    fake=copy.deepcopy(loaded);fake['summary']['minDistanceLower']='999999';fake['summary']['maxPositionWidth']=0
    page.locator('#proof-file').set_input_files({'name':'lying-summary.json','mimeType':'application/json','buffer':json.dumps(fake).encode()})
    page.wait_for_function('ThreeBodyProofUI.result!==null && !ThreeBodyProofUI.busy')
    check('summary is recomputed, never trusted',page.evaluate('ThreeBodyProofUI.result.checks[0].minDistanceLower')==result['checks'][0]['minDistanceLower'])
    bad=copy.deepcopy(loaded);bad['steps'][-1]['end'][0]=['0','0']
    page.locator('#proof-file').set_input_files({'name':'bad-endpoint.json','mimeType':'application/json','buffer':json.dumps(bad).encode()})
    page.wait_for_function("!ThreeBodyProofUI.busy && document.getElementById('proof-progress').textContent.includes('인증하지 못')")
    check('tampered endpoint rejected in browser',page.evaluate('ThreeBodyProofUI.result===null') and page.locator('#proof-export').is_disabled())
    page.locator('#proof-file').set_input_files({'name':'good.json','mimeType':'application/json','buffer':json.dumps(loaded).encode()})
    page.wait_for_function('ThreeBodyProofUI.result!==null && !ThreeBodyProofUI.busy')
    check('valid certificate imports and rechecks',page.evaluate('ThreeBodyProofUI.result.checks[0].complete'))
    page.select_option('#proof-source','pair');page.fill('#proof-time','.7');page.select_option('#proof-order','14');page.select_option('#proof-step','8');page.click('#proof-run')
    page.wait_for_function('ThreeBodyProofUI.result!==null && !ThreeBodyProofUI.busy',timeout=25000)
    pair=page.evaluate('ThreeBodyProofUI.result')
    check('both perturbed certificates complete',all(c['complete'] and c['verified'] for c in pair['checks']))
    check('certified finite-time amplification greater than 2',float(pair['separation']['ratio'][0])>2)
    check('amplification interval is explicit',float(pair['separation']['ratio'][1])<2.129)
    (BASE/'pair_certificate.json').write_text(json.dumps(pair['record'],indent=2))
    page.screenshot(path=str(BASE/'proof_desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844});page.wait_for_timeout(100)
    check('mobile document does not overflow horizontally',page.evaluate('document.documentElement.scrollWidth===innerWidth'))
    check('mobile modal fits viewport',page.locator('#proof-modal .modal').bounding_box()['width']<=390)
    page.screenshot(path=str(BASE/'proof_mobile.png'),full_page=True)
    page.keyboard.press('Escape');check('Escape closes proof modal',not page.locator('#proof-modal').is_visible())
    page.set_viewport_size({'width':1500,'height':1100});page.click('[data-preset="asymmetric"]');page.evaluate('ThreeBodyLab.pause()');page.fill('#mass','1.1')
    page.click('#open-proof');page.select_option('#proof-source','current');page.click('#proof-run')
    check('unapplied initial changes block proof',not page.evaluate('ThreeBodyProofUI.busy') and '먼저' in page.locator('#proof-progress').inner_text())
    page.keyboard.press('Escape');page.click('#apply');page.select_option('#epsilon','.01');page.click('#apply');page.click('#open-proof');page.click('#proof-run')
    check('softened model not silently certified',not page.evaluate('ThreeBodyProofUI.busy') and '연화' in page.locator('#proof-progress').inner_text())
    page.select_option('#proof-source','asymmetric');page.fill('#proof-time','0');page.click('#proof-run')
    page.wait_for_function("!ThreeBodyProofUI.busy && document.getElementById('proof-progress').textContent.includes('인증하지 못')")
    check('zero horizon rejected',page.evaluate('ThreeBodyProofUI.result===null'))
    page.fill('#proof-time','2');page.select_option('#proof-order','16');page.select_option('#proof-step','9');page.click('#proof-run');page.click('#proof-cancel')
    check('worker cancellation stops proof with no certificate',not page.evaluate('ThreeBodyProofUI.busy') and page.evaluate('ThreeBodyProofUI.result===null') and page.locator('#proof-export').is_disabled())
    check('no runtime errors',not errors,errors)
    check('no external network requests',not [u for u in requests if u.startswith(('http:','https:'))])
    (BASE/'proof_browser_results.json').write_text(json.dumps({'browser':'Chromium '+browser.version,'navigation':'about:blank set_content of exact delivered HTML bytes; file:// and Safari not tested','passed':sum(x['passed'] for x in results),'total':len(results),'tests':results,'errors':errors},ensure_ascii=False,indent=2))
    browser.close()
